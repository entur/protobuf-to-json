package no.entur.protobuf.json.plan;

import com.google.protobuf.DescriptorProtos.DescriptorProto;
import com.google.protobuf.DescriptorProtos.EnumDescriptorProto;
import com.google.protobuf.DescriptorProtos.EnumValueDescriptorProto;
import com.google.protobuf.DescriptorProtos.EnumValueOptions;
import com.google.protobuf.DescriptorProtos.FieldDescriptorProto;
import com.google.protobuf.DescriptorProtos.FileDescriptorProto;
import com.google.protobuf.Descriptors.Descriptor;
import com.google.protobuf.Descriptors.EnumDescriptor;
import com.google.protobuf.Descriptors.FileDescriptor;
import com.google.protobuf.DynamicMessage;
import com.google.protobuf.ExtensionLite;
import com.google.protobuf.Message;
import com.google.protobuf.NullValue;
import com.google.protobuf.Syntax;
import com.google.protobuf.util.JsonFormat;
import no.entur.protobuf.json.transcode.TranscodingProtobufJsonWriter;
import org.junit.jupiter.api.Test;

import static com.google.common.truth.Truth.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

public class JsonEnumValueNamesTest {

    private static final String OPTIONS_PROTO = "com.google.protobuf.util.JsonEnumvalueOptionsProto";

    @Test
    public void looksUpCustomNamesWhenProtobufJavaUtilHasTheOption() {
        // protobuf-java-util 4.36 and later, with a protobuf-java its generated code accepts; the build also runs the tests
        // with an older protobuf version
        boolean option;
        try {
            Class.forName(OPTIONS_PROTO);
            option = true;
        } catch (ClassNotFoundException | LinkageError e) {
            option = false;
        }
        assertThat(JsonEnumValueNames.isAvailable()).isEqualTo(option);
    }

    @Test
    public void writesNamesOfValuesWithoutCustomNames() {
        assertThat(JsonEnumValueNames.getJsonName(NullValue.NULL_VALUE.getValueDescriptor())).isEqualTo("NULL_VALUE");
        assertThat(JsonEnumValueNames.getJsonName(Syntax.SYNTAX_PROTO3.getValueDescriptor())).isEqualTo("SYNTAX_PROTO3");
    }

    @Test
    public void writesCustomNames() throws Exception {
        assumeTrue(JsonEnumValueNames.isAvailable(), "no custom enum value JSON names in this protobuf-java-util version");

        // only edition 2026 files can set the option, so the file is built here rather than generated by protoc
        FileDescriptorProto file = FileDescriptorProto.newBuilder()
                .setName("json_enum_value_names_test.proto")
                .setPackage("json_enum_value_names_test")
                .setSyntax("proto3")
                .addEnumType(EnumDescriptorProto.newBuilder()
                        .setName("Color")
                        .addValue(EnumValueDescriptorProto.newBuilder().setName("COLOR_UNSPECIFIED").setNumber(0))
                        .addValue(EnumValueDescriptorProto.newBuilder().setName("COLOR_RED").setNumber(1).setOptions(customName("red"))))
                .addMessageType(DescriptorProto.newBuilder()
                        .setName("Paint")
                        .addField(FieldDescriptorProto.newBuilder()
                                .setName("color")
                                .setNumber(1)
                                .setLabel(FieldDescriptorProto.Label.LABEL_OPTIONAL)
                                .setType(FieldDescriptorProto.Type.TYPE_ENUM)
                                .setTypeName(".json_enum_value_names_test.Color")))
                .build();
        FileDescriptor descriptor = FileDescriptor.buildFrom(file, new FileDescriptor[0]);

        EnumDescriptor color = descriptor.findEnumTypeByName("Color");
        assertThat(JsonEnumValueNames.getJsonName(color.findValueByNumber(1))).isEqualTo("red");
        assertThat(JsonEnumValueNames.getJsonName(color.findValueByNumber(0))).isEqualTo("COLOR_UNSPECIFIED");

        Descriptor paint = descriptor.findMessageTypeByName("Paint");
        DynamicMessage message = DynamicMessage.newBuilder(paint).setField(paint.findFieldByName("color"), color.findValueByNumber(1)).build();
        String json = TranscodingProtobufJsonWriter.newBuilder().build().writeAsString(message);
        assertThat(json).isEqualTo("{\"color\":\"red\"}");
        assertThat(JsonFormat.printer().omittingInsignificantWhitespace().print(message)).isEqualTo(json);
    }

    /**
     * Options with a custom JSON name, by reflection, as the tests also compile with protobuf versions without the option.
     */

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static EnumValueOptions customName(String name) throws ReflectiveOperationException {
        ExtensionLite option = (ExtensionLite) Class.forName(OPTIONS_PROTO).getField("json").get(null);
        Message prototype = (Message) option.getMessageDefaultInstance();
        Message value = prototype.newBuilderForType().setField(prototype.getDescriptorForType().findFieldByName("string"), name).build();
        return EnumValueOptions.newBuilder().setExtension(option, value).build();
    }
}
